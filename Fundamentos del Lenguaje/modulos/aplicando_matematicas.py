import matematicas

# Solicitar al usuario que ingrese los valores
a = float(input("Ingresa el primer número: "))
b = float(input("Ingresa el segundo número: "))

print("Suma:", matematicas.sumar(a, b))
print("Resta:", matematicas.restar(a, b))
print("Multiplicación:", matematicas.multiplicar(a, b))
print("División:", matematicas.dividir(a, b))
